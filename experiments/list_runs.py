"""List the exact command behind every result file, from its .meta.json sidecar.

Every experiment script records its command-line arguments (`argv`) in the
sidecar written next to each CSV. This script groups result files by the
command that produced them and writes results/RUNS.md.

    python experiments/list_runs.py
"""
from __future__ import annotations

import json
import shlex
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"

TITLES = {
    "exp1": "exp1: migration timelines (all methods, 5 seeds)",
    "exp2": "exp2: scheduler signal ablation",
    "exp3": "exp3: adapter ablation (adapter families, seed sweep, query modes)",
    "exp4": "exp4: warm-start graph and k-means construction",
    "exp4b": "exp4b: warm-start IVF inside FAISS",
    "exp5": "exp5: certification (bias, coverage, fire timing, bound and metric sweep)",
    "exp6": "exp6: serving latency and old-index compaction",
    "exp7": "exp7: live-encoder cost of a budget unit",
    "exp8": "exp8: per-query certificate against the truth",
    "exp9": "exp9: scale ladders (Quora, MS MARCO)",
    "exp10": "exp10: Drift-Adapter reproduction and factor checks",
}


def command(argv) -> str:
    if isinstance(argv, list):  # sys.argv as recorded by exp1-exp9
        return "python " + " ".join(shlex.quote(a) for a in argv)
    # exp10 records its parsed arguments
    parts = ["python experiments/exp10_driftadapter_repro.py"]
    for key in ("settings", "np", "runs", "adapters", "directions", "recipe", "tag"):
        v = argv.get(key)
        if v is None:
            continue
        flag = "--" + key
        vals = v if isinstance(v, list) else [v]
        parts.append(flag + " " + " ".join(shlex.quote(str(x)) for x in vals))
    return " ".join(parts)


def family(name: str) -> str:
    stem = name.split("_")[0]
    return "exp4b" if name.startswith("exp4b") else stem


def main() -> None:
    groups: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    derived: dict[str, list[str]] = defaultdict(list)
    for csv in sorted(RES.glob("*.csv")):
        side = csv.with_name(csv.name + ".meta.json")
        if side.exists():
            argv = json.loads(side.read_text()).get("argv")
            if argv is not None:
                groups[family(csv.name)][command(argv)].append(csv.name)
                continue
        base = csv.name.replace("_summary.csv", ".csv")
        derived[family(csv.name)].append(f"{csv.name} (mean and s.d. over runs of {base})")

    lines = ["# Commands behind every result file", "",
             "Generated by `experiments/list_runs.py` from the `argv` recorded in each "
             "`.meta.json` sidecar. Run the commands from the artifact root after the "
             "data-preparation step of the README; each writes the listed files into "
             "`results/`.", ""]
    order = sorted(groups, key=lambda f: (int("".join(c for c in f[3:] if c.isdigit()) or 0), f))
    for fam in order:
        lines += [f"## {TITLES.get(fam, fam)}", ""]
        for cmd, files in groups[fam].items():
            lines += ["```bash", cmd, "```", ""]
            lines += [f"- `{f}`" for f in files] + [""]
        if derived.get(fam):
            lines += ["Summaries derived from the files above:", ""]
            lines += [f"- `{d.split(' ', 1)[0]}` {d.split(' ', 1)[1]}" for d in derived[fam]] + [""]
    (RES / "RUNS.md").write_text("\n".join(lines))
    n_cmd = sum(len(v) for v in groups.values())
    n_files = sum(len(f) for v in groups.values() for f in v.values())
    print(f"wrote results/RUNS.md: {n_cmd} commands covering {n_files} files "
          f"(+{sum(len(v) for v in derived.values())} derived summaries)")


if __name__ == "__main__":
    main()
